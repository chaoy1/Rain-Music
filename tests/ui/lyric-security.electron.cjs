const { app, BrowserWindow, MessageChannelMain } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
process.env.RAIN_DATA_DIR = path.join(root, '.design/lyric-security-portable')
const dataPath = path.join(process.env.RAIN_DATA_DIR, 'userData/RainDatas')
fs.mkdirSync(dataPath, { recursive: true })
fs.writeFileSync(path.join(dataPath, 'config_v2.json'), JSON.stringify({ version: '2.12.6', setting: { version: '2.12.8', 'theme.id': 'mono', 'common.langId': 'zh-cn', 'desktopLyric.enable': false } }))
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const until = async(fn) => { for (let i = 0; i < 120; i++) { const value = await fn(); if (value) return value; await wait(100) } throw new Error('Timed out waiting for lyric window') }
const evaluate = (win, source) => win.webContents.executeJavaScript(source)
const timeout = setTimeout(() => app.exit(1), 60000)
app.on('browser-window-created', (_, main) => {
  main.webContents.once('did-finish-load', async() => {
    if (!main.webContents.getURL().includes('index.html')) return
    try {
      await until(() => evaluate(main, `!!window.rainData?.updateSetting`))
      await until(() => global.envParams?.workAreaSize?.width)
      await evaluate(main, `window.rainData.updateSetting({'desktopLyric.enable':true});void 0`)
      const lyric = await until(() => BrowserWindow.getAllWindows().find(win => win.webContents.getURL().includes('lyric.html')))
      await until(() => evaluate(lyric, `!!document.querySelector('[data-lyric-close]')`))
      const preferences = lyric.webContents.getLastWebPreferences()
      for (const [key, value] of Object.entries({ nodeIntegration: false, nodeIntegrationInWorker: false, contextIsolation: true, webSecurity: true, sandbox: true })) assert.equal(preferences[key], value, key)
      assert.deepEqual(await evaluate(lyric, `[typeof require, typeof process, typeof Buffer, typeof module]`), ['undefined', 'undefined', 'undefined', 'undefined'])
      assert.equal(await evaluate(lyric, `Object.keys(window.lyricBridge).some(key=>['send','invoke','ipcRenderer','on'].includes(key))`), false)
      assert.equal(await evaluate(lyric, `(async()=>{try{await window.lyricBridge.updateSetting({'player.isMute':true});return false}catch(e){return /Invalid/.test(e.message)}})()`), true)
      await evaluate(lyric, `window.qaChanges=[];window.qaRemove=window.lyricBridge.onSettingChanged(value=>window.qaChanges.push(value));void 0`)
      lyric.webContents.send('winLyric_on_config_change', { 'desktopLyric.style.opacity': 99 })
      await until(() => evaluate(lyric, `window.qaChanges.length===1`))
      assert.equal(await evaluate(lyric, `'sender' in window.qaChanges[0] || 'event' in window.qaChanges[0]`), false)
      await evaluate(lyric, `window.qaRemove();window.qaRemove();void 0`)
      lyric.webContents.send('winLyric_on_config_change', { 'desktopLyric.style.opacity': 98 })
      await wait(150)
      assert.equal(await evaluate(lyric, `window.qaChanges.length`), 1)
      const { port1, port2 } = new MessageChannelMain()
      port1.on('message', ({ data }) => {
        if (data.action === 'get_info') port1.postMessage({ action: 'set_info', data: { id: 'security-test', singer: '测试', name: '测试', album: '', lrc: '[00:00.00]雨声\n[00:02.00]晨光', tlrc: null, rlrc: null, rainlrc: null, isPlay: false, line: 0, played_time: 0 } })
      })
      port1.start()
      lyric.webContents.postMessage('winLyric_provide_main_window_channel', null, [port2])
      await until(() => evaluate(lyric, `document.querySelector('[data-current-lyric]')?.textContent.includes('雨声')`))
      port1.postMessage({ action: 'set_play', data: 2100 })
      await until(() => evaluate(lyric, `document.querySelector('[data-current-lyric]')?.textContent.includes('晨光')`))
      port1.postMessage({ action: 'set_play', data: 100 })
      await until(() => evaluate(lyric, `document.querySelector('[data-current-lyric]')?.textContent.includes('雨声')`))
      assert.equal(await evaluate(lyric, `!!document.querySelector('[data-current-lyric] .line')`), true)
      port1.postMessage({ action: 'set_lyric', data: { lrc: '[00:00.00]雨声\n[00:03.00]晨光', rainlrc: '[00:00.00]<0,1500>雨<1500,1500>声\n[00:03.00]<0,1500>晨<1500,1500>光' } })
      port1.postMessage({ action: 'set_play', data: 500 })
      await until(() => evaluate(lyric, `(()=>{const span=document.querySelector('[data-current-lyric] .font-lrc>span');if(!span)return false;const style=getComputedStyle(span),progress=parseFloat(style.backgroundSize);return progress>0&&progress<100&&style.backgroundClip==='text'})()`))
      port1.postMessage({ action: 'set_pause' })
      await wait(100)
      const pausedProgress = await evaluate(lyric, `getComputedStyle(document.querySelector('[data-current-lyric] .font-lrc>span')).backgroundSize`)
      await wait(150)
      assert.equal(await evaluate(lyric, `getComputedStyle(document.querySelector('[data-current-lyric] .font-lrc>span')).backgroundSize`), pausedProgress)
      assert.equal(lyric.isAlwaysOnTop(), true)
      const before = lyric.getBounds()
      await evaluate(lyric, `window.lyricBridge.setWindowBounds({x:-10,y:-10,w:${before.width},h:${before.height}});void 0`)
      await until(() => lyric.getBounds().x !== before.x || lyric.getBounds().y !== before.y)
      await evaluate(lyric, `document.querySelector('[data-lyric-lock]').click();void 0`)
      await until(() => global.rain.appSetting['desktopLyric.isLock'] === true)
      await evaluate(lyric, `document.querySelector('[data-lyric-close]').click();void 0`)
      await until(() => lyric.isDestroyed())
      console.log('PASS real lyric sandbox, constrained bridge, unsubscribe, MessagePort karaoke, drag, always-on-top, lock and close')
      port1.close()
      clearTimeout(timeout)
      app.exit(0)
    } catch (error) { console.error(error); app.exit(1) }
  })
})
require(path.join(root, 'dist/main.js'))
